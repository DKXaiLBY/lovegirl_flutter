    for (final cities in citiesByLetter.values) {
      list.addAll(cities);
    }
    return list;
  }

  /// 搜索城市
  static List<String> search(String keyword) {
    if (keyword.isEmpty) return [];
    final kw = keyword.toLowerCase();
    return allCities.where((c) => c.contains(kw)).toList();
